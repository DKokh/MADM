"""Put published assay measurements on the scale MADM's models were trained on.

WHY. Developability measurements pooled from independent publications are not on
one scale: a retention time in minutes and the same quantity in column volumes, a
polyreactivity ratio and the same ratio x10. Combined without correction, the
offset between two laboratories looks exactly like a difference between two
antibodies -- it inflates pooled correlations, and nothing in the data complains.

A model trained on the harmonised scale must be given data on that scale. Feeding
it raw values from a source whose factor is 3.8 (Ginkgo HIC) does not produce a
slightly worse prediction; it produces a confident wrong one.

WHAT THIS DOES. For each (assay, source) in the training corpus there is a linear
transform

    harmonised = a * value + b

recovered from molecules recorded in both scales. The coefficients are in
`_rescale_tables.py`, generated by `Scripts/fit_rescale_transforms.py`.

    from madm.rescale import rescale, sources_for
    df["HIC_h"] = rescale(df.HIC, df.source, "HIC")

    python -m madm.rescale --list-sources --assay HIC
    python -m madm.rescale --table mine.xlsx --assay HIC --out mine_rescaled.xlsx

SMP AND OVALBUMIN are listed as `identity`: their published values are already on
the training scale. This is not an omission -- it was checked on molecules
measured by two sources, where the raw values agree (SMP: 118 molecules, median
ratio 1.02) while applying a conversion would introduce an offset rather than
remove one.

IF YOUR DATA IS FROM A SOURCE THAT IS NOT LISTED there is no transform for it and
this module will not invent one: those values come back as NaN rather than being
passed through unchanged, because a raw value sitting silently in a harmonised
column is the failure this exists to prevent. A transform can only be derived
from molecules measured on BOTH scales -- measure a few antibodies that already
appear in the corpus, then run the fitting script. Without such anchors the
offset and the biology cannot be separated, by this or any other method.
"""
from __future__ import annotations

import difflib
from typing import Dict, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

from ._rescale_tables import REFERENCES, TRANSFORMS

try:                                    # added 2026-10; older generated tables lack it
    from ._rescale_tables import TRAINING_COUNTS
except ImportError:
    TRAINING_COUNTS = {}

__all__ = ["rescale", "transform_for", "sources_for", "assays", "rescale_table"]

# Column names each assay is usually stored under, most specific first. Used only
# to guess; every entry point takes explicit names too.
VALUE_COLUMNS = {
    "AC-SINS": ["AC_SINS", "AC-SINS"], "BVP": ["BVP"], "DNA": ["DNA"],
    "HIC": ["HIC"], "Hep": ["Hep", "HAC"], "Insulin": ["Insulin"],
    "Ovalbumin": ["Ovalbumin"], "SMP": ["SMP", "PSR"],
}
SOURCE_COLUMNS = {
    "AC-SINS": ["source_AC_SINS_detailed", "source_AC_SINS"],
    "BVP": ["source_BVP"], "DNA": ["source_DNA_extended", "source_DNA"],
    "HIC": ["source_HIC"], "Hep": ["source_Hep"],
    "Insulin": ["source_Insulin_detailed", "source_Insulin"],
    "Ovalbumin": ["source_Ovalbumin_deteiled", "source_Ovalbumin_detailed",
                  "source_Ovalbumin"],
    "SMP": ["source_SMP_detailed", "source_SMP"],
}


def assays() -> list:
    """Assays with a published transform table."""
    return sorted(TRANSFORMS)


def sources_for(assay: str) -> list:
    """Recognised source names for `assay`, in the spelling they must match."""
    _check_assay(assay)
    return sorted(TRANSFORMS[assay])


def transform_for(assay: str, source: str) -> Optional[Tuple[float, float, str, int]]:
    """(a, b, status, n) or None if the source is not recognised."""
    _check_assay(assay)
    return TRANSFORMS[assay].get(str(source).strip())


def _check_assay(assay: str) -> None:
    if assay not in TRANSFORMS:
        raise KeyError(f"no transforms for assay {assay!r}. "
                       f"Have: {sorted(TRANSFORMS)}")


def rescale(values, sources, assay: str, *, strict: bool = False,
            allow: Sequence[str] = ("exact", "approx", "identity", "single_row"),
            return_status: bool = False):
    """Harmonise `values` according to each molecule's `sources`.

    Unrecognised source, unusable status or missing value -> NaN. Never the
    original value: a raw number silently occupying a harmonised column is the
    error this module exists to prevent, and it cannot be detected downstream.

    strict=True raises instead, for a pipeline that should stop rather than
    produce a table with holes in it.

    `allow` filters by status. The default accepts `single_row`, where the slope
    was assumed rather than measured from one molecule; pass
    ("exact", "approx", "identity") to refuse those.
    """
    _check_assay(assay)
    v = pd.to_numeric(pd.Series(values).reset_index(drop=True), errors="coerce").to_numpy(float)
    s = pd.Series(sources).reset_index(drop=True).astype(str).str.strip().to_numpy()
    if len(v) != len(s):
        raise ValueError(f"values and sources differ in length: {len(v)} vs {len(s)}")

    out = np.full(len(v), np.nan)
    status = np.array(["no_transform"] * len(v), dtype=object)
    table = TRANSFORMS[assay]
    unknown, refused = set(), set()
    for i in range(len(v)):
        hit = table.get(s[i])
        if hit is None:
            if np.isfinite(v[i]):
                unknown.add(s[i])
            continue
        a, b, st, _ = hit
        if st not in allow:
            refused.add(f"{s[i]} ({st})")
            status[i] = f"refused:{st}"
            continue
        status[i] = st
        if np.isfinite(v[i]):
            out[i] = a * v[i] + b

    if strict and (unknown or refused):
        raise ValueError(
            f"{assay}: cannot harmonise "
            + (f"{len(unknown)} unrecognised source(s) {sorted(unknown)}" if unknown else "")
            + ("; " if unknown and refused else "")
            + (f"refused by status: {sorted(refused)}" if refused else ""))
    if unknown:
        known = sorted(table)
        msg = [f"[rescale] {assay}: NO TRANSFORM for {len(unknown)} source name(s); "
               "those values are NaN"]
        for u in sorted(unknown):
            near = difflib.get_close_matches(u, known, n=2, cutoff=0.6)
            msg.append(f"            {u!r}"
                       + (f"   did you mean {' or '.join(map(repr, near))}?" if near else ""))
        print("\n".join(msg))
    if refused:
        print(f"[rescale] {assay}: refused by status filter: {sorted(refused)}")

    return (out, status) if return_status else out


def rescale_table(df: pd.DataFrame, assay: str, *, value_column: Optional[str] = None,
                  source_column: Optional[str] = None,
                  out_column: Optional[str] = None, **kw) -> pd.DataFrame:
    """`rescale` over a DataFrame, adding `<value>_harmonised` and its status."""
    _check_assay(assay)
    vcol = value_column or next((c for c in VALUE_COLUMNS.get(assay, [assay])
                                 if c in df.columns), None)
    if vcol is None:
        raise KeyError(f"no value column for {assay!r} (tried "
                       f"{VALUE_COLUMNS.get(assay, [assay])}). Pass value_column=.")
    scol = source_column or next((c for c in SOURCE_COLUMNS.get(assay, []) + ["source"]
                                  if c in df.columns), None)
    if scol is None:
        raise KeyError(f"no source column for {assay!r} (tried "
                       f"{SOURCE_COLUMNS.get(assay, []) + ['source']}). "
                       "Pass source_column=.")
    out, status = rescale(df[vcol], df[scol], assay, return_status=True, **kw)
    col = out_column or f"{vcol}_harmonised"
    d = df.copy()
    d[col] = out
    d[col + "_status"] = status
    return d


# --------------------------------------------------------------------------- #
def _cli(argv=None):
    import argparse
    p = argparse.ArgumentParser(prog="python -m madm.rescale", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--list-sources", action="store_true")
    p.add_argument("--assay", choices=assays())
    p.add_argument("--table")
    p.add_argument("--out")
    p.add_argument("--value-column")
    p.add_argument("--source-column")
    p.add_argument("--out-column")
    p.add_argument("--strict", action="store_true",
                   help="fail instead of writing NaN for unrecognised sources")
    p.add_argument("--no-assumed", action="store_true",
                   help="refuse transforms whose slope was assumed from one molecule")
    a = p.parse_args(argv)

    if a.list_sources:
        for assay in ([a.assay] if a.assay else assays()):
            trained = TRAINING_COUNTS.get(assay, {})
            print(f"\n{assay}   ({len(TRANSFORMS[assay])} sources)")
            for src, (m, c, st, n) in sorted(TRANSFORMS[assay].items()):
                eq = ("value is already on the training scale" if st == "identity"
                      else f"harmonised = {m:g} * x" + (f" {c:+g}" if c else ""))
                flag = "" if st in ("exact", "identity") else f"   [{st}]"
                # n is how many molecules the TRANSFORM was fitted from; train is
                # how many distinct sequences the source contributed to training.
                # They differ, and conflating them overstates small sources.
                tr = trained.get(src)
                cols = f"n={n:<4d}" + (f" train={tr:<5d}" if tr is not None else "")
                print(f"   {src:<34s} {cols} {eq}{flag}")
                ref = REFERENCES.get(src)
                if ref and ref[0]:
                    print(f"   {'':34s}   {ref[0]}" + (f"  {ref[1]}" if ref[1] else ""))
        return 0

    miss = [f"--{k}" for k in ("table", "assay", "out") if not getattr(a, k)]
    if miss:
        p.error(f"missing {', '.join(miss)}. Use --list-sources to see the "
                "recognised source names.")

    read = (pd.read_excel if a.table.lower().endswith((".xlsx", ".xls")) else pd.read_csv)
    df = read(a.table)
    allow = (("exact", "approx", "identity") if a.no_assumed
             else ("exact", "approx", "identity", "single_row"))
    d = rescale_table(df, a.assay, value_column=a.value_column,
                      source_column=a.source_column, out_column=a.out_column,
                      strict=a.strict, allow=allow)
    col = [c for c in d.columns if c.endswith("_harmonised")
           or c == a.out_column][-1] if a.out_column else \
        [c for c in d.columns if c.endswith("_harmonised")][-1]
    n_ok = int(np.isfinite(d[col]).sum())
    print(f"[rescale] {a.assay}: {n_ok}/{len(d)} rows harmonised")
    (d.to_excel if a.out.lower().endswith((".xlsx", ".xls")) else d.to_csv)(a.out, index=False)
    print(f"[rescale] wrote {a.out}   (new columns {col!r}, {col}_status)")
    return 0


if __name__ == "__main__":
    raise SystemExit(_cli())
